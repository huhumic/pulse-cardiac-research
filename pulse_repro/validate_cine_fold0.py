"""Orchestrate audited ED/ES full-3D Cine V1.5/V2 validation.

This module does NOT modify training, inference, or checkpoints. It calls the
existing evaluate_cine_v2 CLI and verifies its outputs. Full-fold scores are
internal checkpoint-selection validation, not an independent test set.

Usage: python -m pulse_repro.validate_cine_fold0 --help
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
import math
import random
import subprocess
import sys
from pathlib import Path
from typing import Any

CLASSES = ("RV", "Myo", "LV")
PHASES = {"ED", "ES"}
MODELS = ("V1.5", "V2")
EPOCHS = {"V1.5": 84, "V2": 91}
N_PATIENTS = 20
N_VOLUMES = 40


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(2**20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def load_csv(path: Path, *, full_fold: bool = True) -> dict[tuple[str, str], dict[str, Any]]:
    """Strictly validate a per_volume.csv generated by a volume evaluator."""
    if not path.is_file():
        raise FileNotFoundError(path)
    with path.open(newline="", encoding="utf-8-sig") as f:
        reader = csv.DictReader(f)
        mandatory = {"patient", "phase", *(f"{c}_dice" for c in CLASSES)}
        if reader.fieldnames is None or not mandatory.issubset(reader.fieldnames):
            raise ValueError(f"CSV missing mandatory columns: {mandatory - set(reader.fieldnames or [])}")
        rows: dict[tuple[str, str], dict[str, Any]] = {}
        for raw in reader:
            pid, phase = raw["patient"], raw["phase"]
            if not pid or phase not in PHASES:
                raise ValueError(f"Invalid patient/phase: {pid}/{phase}")
            key = (pid, phase)
            if key in rows:
                raise ValueError(f"Duplicate patient/phase: {key}")
            row = {"patient": pid, "phase": phase}
            for c in CLASSES:
                val = float(raw[f"{c}_dice"])
                if not math.isfinite(val) or not 0 <= val <= 1:
                    raise ValueError(f"Invalid {c} 3D Dice at {key}: {val}")
                row[c] = val
            rows[key] = row
    patient_phases: dict[str, set[str]] = {}
    for pid, phase in rows:
        patient_phases.setdefault(pid, set()).add(phase)
    if any(phases != PHASES for phases in patient_phases.values()):
        raise ValueError("Every evaluated patient must have exactly ED and ES")
    if full_fold and (len(rows) != N_VOLUMES or len(patient_phases) != N_PATIENTS):
        raise ValueError(f"Incomplete Fold 0: {len(patient_phases)} patients / {len(rows)} volumes")
    if not full_fold and not rows:
        raise ValueError("No validated volumes")
    return rows


def by_patient(rows: dict[tuple[str, str], dict[str, Any]]) -> dict[str, dict[str, float]]:
    grouped: dict[str, dict[str, float]] = {}
    for (pid, _), row in rows.items():
        item = grouped.setdefault(pid, {c: 0.0 for c in CLASSES})
        for c in CLASSES:
            item[c] += row[c] / 2.0
    return grouped


def summary_stats(rows: dict[tuple[str, str], dict[str, Any]]) -> dict[str, Any]:
    pats = by_patient(rows)
    n = len(pats)
    scores = {c: sum(r[c] for r in pats.values()) / n for c in CLASSES}
    return {"n_patients": n, "n_volumes": len(rows), "per_class_dice": scores,
            "mean_dice": sum(scores.values()) / len(scores),
            "patient_ids": sorted(pats)}


def paired_delta(baseline: dict, candidate: dict, *, seed: int = 42,
                 n_bootstrap: int = 5000) -> dict[str, Any]:
    if set(baseline) != set(candidate):
        missing = sorted(set(baseline) ^ set(candidate))
        raise ValueError(f"Cannot pair cohorts with different patient/phase keys: {missing[:5]}")
    a, b = by_patient(baseline), by_patient(candidate)
    patients = sorted(a)
    if not patients:
        raise ValueError("Empty paired cohort")
    diffs = {c: [b[pid][c] - a[pid][c] for pid in patients] for c in CLASSES}
    diffs["Mean"] = [sum(b[p][c] - a[p][c] for c in CLASSES) / len(CLASSES) for p in patients]
    rng = random.Random(seed)
    result: dict[str, Any] = {"n_paired_patients": len(patients),
                              "n_bootstrap": n_bootstrap, "bootstrap_seed": seed,
                              "delta_candidate_minus_reference": {}}
    for metric, data in diffs.items():
        n = len(data)
        draws = sorted(sum(data[rng.randrange(n)] for _ in range(n)) / n
                       for _ in range(n_bootstrap))
        low = draws[int(.025 * (n_bootstrap - 1))]
        high = draws[int(.975 * (n_bootstrap - 1))]
        result["delta_candidate_minus_reference"][metric] = {
            "mean": sum(data) / n, "bootstrap_95pct_CI": [low, high],
            "improved_patients": sum(v > 0 for v in data),
            "tied_patients": sum(v == 0 for v in data),
        }
    return result


def validate_checkpoint(path: Path, *, variant: str, fold: int) -> dict[str, Any]:
    """Check actual best checkpoint metadata, not a directory name."""
    if not path.is_file():
        raise FileNotFoundError(path)
    import torch
    ck = torch.load(str(path), map_location="cpu", weights_only=True)
    if ck.get("variant") != "cine-reliability-v2":
        raise ValueError(f"{variant}: incorrect checkpoint variant")
    if ck.get("protocol_version") != "audited-directional-v2":
        raise ValueError(f"{variant}: incompatible temporal protocol")
    if int(ck.get("fold", -1)) != fold:
        raise ValueError(f"{variant}: checkpoint fold mismatch")
    if not ck.get("use_temporal", False):
        raise ValueError(f"{variant}: temporal model expected")
    structure = bool(ck.get("use_structure", True))
    if structure != (variant == "V2"):
        raise ValueError(f"{variant}: use_structure flag mismatch")
    epoch = int(ck.get("epoch", -1))
    if epoch != EPOCHS[variant]:
        raise ValueError(f"{variant}: expected best E{EPOCHS[variant]}, found E{epoch}; inspect run logs")
    score = float(ck.get("best_dice", float("nan")))
    if not math.isfinite(score) or not 0 <= score <= 1:
        raise ValueError(f"{variant}: invalid selection Dice")
    if not isinstance(ck.get("model"), dict):
        raise ValueError(f"{variant}: checkpoint model state missing")
    del ck
    return {"variant": variant, "epoch": epoch, "best_slice_dice": score,
            "checkpoint": str(path.resolve()), "checkpoint_sha256": sha256_file(path)}


def check_run(run_dir: Path, *, variant: str, control: str,
              checkpoint_info: dict[str, Any], full_fold: bool) -> dict[tuple, dict]:
    summary_path = run_dir / "summary.json"
    if not summary_path.is_file():
        raise FileNotFoundError(summary_path)
    data = json.loads(summary_path.read_text(encoding="utf-8"))
    checks = {
        "variant": variant, "fold": 0, "seed": 42, "tta": True,
        "precision": "fp32", "temporal_control": control,
        "checkpoint_epoch": checkpoint_info["epoch"],
        "checkpoint_sha256": checkpoint_info["checkpoint_sha256"],
        "full_fold": full_fold,
        "n_volumes": N_VOLUMES if full_fold else 2,
        "n_patients": N_PATIENTS if full_fold else 1,
    }
    for key, val in checks.items():
        if data.get(key) != val:
            raise ValueError(f"{run_dir}: {key} expected {val!r}, found {data.get(key)!r}")
    rows = load_csv(run_dir / "per_volume.csv", full_fold=full_fold)
    stats = summary_stats(rows)
    if abs(stats["mean_dice"] - data["mean_dice"]) > 1e-9:
        raise ValueError(f"{run_dir}: stored Mean Dice does not match original per-volume Dice")
    return rows


def run_one(*, acdc_root: Path, pulse_root: Path, weights: Path, output: Path,
            name: str, control: str, metadata: dict[str, Any], smoke: bool,
            dry_run: bool, resume: bool) -> dict | None:
    variant = metadata["variant"]
    target = output / ("smoke" if smoke else "full") / name
    if target.exists() and any(target.iterdir()):
        if not resume:
            raise FileExistsError(f"Existing run output (not overwritten): {target}; use --resume only for completed runs")
        return check_run(target, variant=variant, control=control,
                         checkpoint_info=metadata, full_fold=not smoke)
    cmd = [sys.executable, "-m", "pulse_repro.evaluate_cine_v2",
           "--acdc-root", str(acdc_root), "--pulse-root", str(pulse_root),
           "--weights", str(weights), "--out-dir", str(target),
           "--fold", "0", "--tta", "--precision", "fp32",
           "--temporal-control", control]
    if smoke:
        cmd.extend(("--max-patients", "1"))
    print("RUN:", " ".join(cmd), flush=True)
    if dry_run:
        return None
    subprocess.run(cmd, check=True)
    return check_run(target, variant=variant, control=control,
                     checkpoint_info=metadata, full_fold=not smoke)


def run(args: argparse.Namespace) -> dict[str, Any] | None:
    if not args.acdc_root.is_dir() or not (args.acdc_root / "training").is_dir():
        raise FileNotFoundError("Prepared ACDC root/training not found")
    if not args.pulse_root.is_dir():
        raise FileNotFoundError("PULSE upstream source not found")
    if not (args.acdc_root / "adapter_manifest.json").is_file():
        raise FileNotFoundError("ACDC adapter_manifest.json required for real 4D cine lookup")
    checkpoints = {"V1.5": args.v15_weights, "V2": args.v2_weights}
    meta = {name: validate_checkpoint(path, variant=name, fold=0)
            for name, path in checkpoints.items()}
    output: Path = args.out_dir
    jobs: list[tuple[str, str]] = [(name, "correct") for name in MODELS]
    if args.controls in ("v2", "both"):
        jobs += [("V2", "swap"), ("V2", "repeat-target")]
    if args.controls == "both":
        jobs += [("V1.5", "swap"), ("V1.5", "repeat-target")]
    results = {}
    for name, control in jobs:
        label = name.replace(".", "") + "_" + control.replace("-", "_")
        results[label] = run_one(
            acdc_root=args.acdc_root, pulse_root=args.pulse_root,
            weights=checkpoints[name], output=output, name=label,
            control=control, metadata=meta[name], smoke=args.smoke,
            dry_run=args.dry_run, resume=args.resume)
    if args.smoke or args.dry_run:
        print("SMOKE/DRY RUN: no formal 40-volume summary is produced", flush=True)
        return None
    for name in results:
        if results[name] is None:
            raise RuntimeError("Unexpected empty result")
    reference_keys = set(next(iter(results.values())))
    for label, rows in results.items():
        if set(rows) != reference_keys:
            raise ValueError(f"Different patient/ED/ES keys in {label}")
    summaries = {label: summary_stats(rows) for label, rows in results.items()}
    comparisons = {"V2_minus_V1.5": paired_delta(results["V15_correct"], results["V2_correct"])}
    if args.baseline_v1:
        baseline = load_csv(args.baseline_v1)
        comparisons["V2_minus_V1"] = paired_delta(baseline, results["V2_correct"])
        comparisons["V1.5_minus_V1"] = paired_delta(baseline, results["V15_correct"])
    if args.baseline_pulse:
        baseline = load_csv(args.baseline_pulse)
        comparisons["V2_minus_PULSE"] = paired_delta(baseline, results["V2_correct"])
    for name in MODELS:
        label = name.replace(".", "")
        for control in ("swap", "repeat-target"):
            alternate = label + "_" + control.replace("-", "_")
            if alternate in results:
                comparisons[name + "_correct_minus_" + control] = paired_delta(
                    results[alternate], results[label + "_correct"])
    manifest = {"protocol": "ACDC 100 labeled training patients; stratified Fold 0 80/20",
                "split_role": "checkpoint-selection validation, NOT independent test",
                "n_patients": N_PATIENTS, "n_volumes": N_VOLUMES,
                "metric": "3D Dice; per-patient ED/ES mean, then class-macro mean",
                "tta": "4 synchronized flips; average softmax", "precision": "fp32",
                "checkpoints": meta, "scores": summaries, "paired_comparisons": comparisons}
    output.mkdir(parents=True, exist_ok=True)
    target = output / "validation_manifest.json"
    if target.exists() and not args.resume:
        raise FileExistsError(f"Manifest already exists: {target}")
    temp = target.with_suffix(".json.part")
    temp.write_text(json.dumps(manifest, indent=2, ensure_ascii=False), encoding="utf-8")
    temp.replace(target)
    print("VERIFIED SUMMARY:", target)
    for label, stats in summaries.items():
        print(f"{label:26s} mean 3D Dice = {stats['mean_dice']:.6f}  {stats['per_class_dice']}")
    for name, comp in comparisons.items():
        print(name, "paired mean Delta:", comp["delta_candidate_minus_reference"]["Mean"])
    return manifest


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--acdc-root", type=Path, required=True)
    parser.add_argument("--pulse-root", type=Path, required=True)
    parser.add_argument("--v15-weights", type=Path, required=True)
    parser.add_argument("--v2-weights", type=Path, required=True)
    parser.add_argument("--out-dir", type=Path, required=True)
    parser.add_argument("--baseline-v1", type=Path, default=None,
                        help="Optional matching Fold-0 V1 per_volume.csv for paired analysis")
    parser.add_argument("--baseline-pulse", type=Path, default=None,
                        help="Optional matching Fold-0 PULSE per_volume.csv for paired analysis")
    parser.add_argument("--controls", choices=("none", "v2", "both"), default="none",
                        help="Optional counterfactuals; default evaluates only correct real Cine inputs")
    parser.add_argument("--smoke", action="store_true", help="One patient only; never treated as full Fold-0")
    parser.add_argument("--dry-run", action="store_true", help="Print commands after checkpoint preflight")
    parser.add_argument("--resume", action="store_true", help="Reuse only complete checksum-verified outputs")
    args = parser.parse_args()
    run(args)


if __name__ == "__main__":
    main()
